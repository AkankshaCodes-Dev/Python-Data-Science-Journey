# Day 18 - Tuple Methods Practice Tasks


# Task 1: Count how many times 10 appears

numbers = (10, 20, 10, 30, 10, 40)

print(numbers.count(10))


# Task 2: Find the position of "Mango"

fruits = ("Apple", "Banana", "Mango", "Orange")

print(fruits.index("Mango"))


# Task 3: Create a Tuple containing your name, age and course

student = ("Akanksha", 20, "BCA")

print(student)


# Task 4: Unpack the student Tuple

name, age, course = student

print(name)
print(age)
print(course)


# Task 5: Create a marks Tuple and unpack it

marks = (85, 90, 78)

maths, science, english = marks

print("Maths:", maths)
print("Science:", science)
print("English:", english)


# Task 6: Create a Tuple with repeated values

numbers = (5, 10, 5, 20, 5, 30)

print(numbers.count(5))


# Task 7: Find the position of 20

print(numbers.index(20))
