# Day 16 - List Methods Practice Tasks


# Task 1: Add an item to a list using append()

fruits = ["Apple", "Banana", "Mango"]

fruits.append("Orange")

print(fruits)


# Task 2: Insert an item at a specific position

fruits = ["Apple", "Banana", "Mango"]

fruits.insert(1, "Orange")

print(fruits)


# Task 3: Remove an item using remove()

fruits = ["Apple", "Banana", "Mango"]

fruits.remove("Banana")

print(fruits)


# Task 4: Remove an item using pop()

fruits = ["Apple", "Banana", "Mango"]

fruits.pop(1)

print(fruits)


# Task 5: Sort a list

numbers = [50, 10, 40, 20, 30]

numbers.sort()

print(numbers)


# Task 6: Reverse a list

numbers = [1, 2, 3, 4, 5]

numbers.reverse()

print(numbers)


# Task 7: Find the position of an item

fruits = ["Apple", "Banana", "Mango"]

print(fruits.index("Mango"))


# Task 8: Count occurrences of an item

numbers = [10, 20, 10, 30, 10, 40]

print(numbers.count(10))


# Task 9: Clear a list

numbers = [1, 2, 3, 4, 5]

numbers.clear()

print(numbers)
