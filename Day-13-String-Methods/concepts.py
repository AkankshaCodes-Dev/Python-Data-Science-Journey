# Day 13 - String Methods


# Example 1: lower()

text = "PYTHON"

print(text.lower())


# Example 2: upper()

text = "python"

print(text.upper())


# Example 3: strip()

text = "   Hello Python   "

print(text.strip())


# Example 4: replace()

text = "I like Java"

print(text.replace("Java", "Python"))


# Example 5: find()

text = "Hello Python"

print(text.find("Python"))


# Example 6: count()

text = "banana"

print(text.count("a"))


# Example 7: split()

text = "Python is easy"

words = text.split()

print(words)
