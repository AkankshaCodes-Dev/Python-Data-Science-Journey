# Day 13 - String Methods Practice Tasks


# Task 1: Convert a string to lowercase

text = "PYTHON IS FUN"

print(text.lower())


# Task 2: Convert a string to uppercase

text = "python is fun"

print(text.upper())


# Task 3: Remove spaces from the beginning and end

text = "   Hello Python   "

print(text.strip())


# Task 4: Replace "Java" with "Python"

text = "I am learning Java"

print(text.replace("Java", "Python"))


# Task 5: Find the position of "Python"

text = "I love Python"

print(text.find("Python"))


# Task 6: Count how many times "a" appears

text = "banana"

print(text.count("a"))


# Task 7: Split a sentence into words

text = "Python is easy to learn"

print(text.split())
