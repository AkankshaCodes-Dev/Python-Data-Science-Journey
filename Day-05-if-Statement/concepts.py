# Day 5 - if Statement

# Basic if statement
age = 20

if age >= 18:
    print("You are an adult.")


# Checking a number
number = 10

if number > 0:
    print("The number is positive.")


# Using equality
name = "Akanksha"

if name == "Akanksha":
    print("Name matched.")


# if with user input
marks = int(input("Enter your marks: "))

if marks >= 40:
    print("You passed.")
