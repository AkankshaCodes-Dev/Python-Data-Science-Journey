# Day 15 - Lists Basics Practice Tasks


# Task 1: Create a student marks list

marks = [85, 90, 78, 92, 88]

print(marks)


# Task 2: Print the first item

print(marks[0])


# Task 3: Print the last item

print(marks[-1])


# Task 4: Change one element

marks[2] = 80

print(marks)


# Task 5: Print all elements one by one

for mark in marks:
    print(mark)


# Task 6: Find the length of the list

print(len(marks))
