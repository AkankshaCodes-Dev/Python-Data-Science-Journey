# Day 12 - Strings Practice Tasks


# Task 1: Create a string containing your name

name = "Akanksha"

print(name)


# Task 2: Print the first character of your name

print(name[0])


# Task 3: Print the last character of your name

print(name[-1])


# Task 4: Print the first three characters of your name

print(name[0:3])


# Task 5: Find the length of your name

print(len(name))


# Task 6: Print each character of your name using a for loop

for character in name:
    print(character)
