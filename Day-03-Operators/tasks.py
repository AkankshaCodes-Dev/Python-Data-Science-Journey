# Day 3 - Operators Practice Tasks

# Task 1: Arithmetic operations
a = 20
b = 5

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)


# Task 2: Practice // and %
num = 17

print("Floor Division:", num // 5)
print("Remainder:", num % 5)


# Task 3: Practice exponent
number = 2

print("Square:", number ** 2)
print("Cube:", number ** 3)


# Task 4: Compare two numbers
x = 10
y = 20

print(x == y)
print(x != y)
print(x > y)
print(x < y)


# Task 5: Logical operators
age = 20

print(age >= 18 and age <= 25)
print(age < 18 or age > 25)
print(not(age < 18))
