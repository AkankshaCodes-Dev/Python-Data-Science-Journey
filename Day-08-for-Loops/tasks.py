# Day 8 - for Loop Practice Tasks


# Task 1: Print numbers from 1 to 10

for i in range(1, 11):
    print(i)


# Task 2: Print even numbers from 1 to 20

for i in range(2, 21, 2):
    print(i)


# Task 3: Print multiplication table of 5

for i in range(1, 11):
    print(5 * i)


# Task 4: Print your name 5 times

for i in range(5):
    print("Akanksha")


# Task 5: Reverse counting from 10 to 1

for i in range(10, 0, -1):
    print(i)
